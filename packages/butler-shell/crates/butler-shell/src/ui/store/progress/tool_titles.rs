fn find(table: Table, key: &str) -> Option<&'static str> {
    table
        .iter()
        .find(|(name, _)| *name == key)
        .map(|(_, text)| *text)
}

/// `guided.tools[name]`.
pub(crate) fn tool(lang: Lang, name: &str) -> Option<&'static str> {
    find(
        match lang {
            Lang::En => TOOLS_EN,
            Lang::Ko => TOOLS_KO,
        },
        name,
    )
}

/// `guided.tools.fallback`.
pub(crate) fn tool_fallback(lang: Lang) -> &'static str {
    tool(lang, "fallback").unwrap_or_default()
}

/// `progress.operations[name]`.
pub(crate) fn operation(lang: Lang, name: &str) -> Option<&'static str> {
    find(
        match lang {
            Lang::En => OPERATIONS_EN,
            Lang::Ko => OPERATIONS_KO,
        },
        name,
    )
}
