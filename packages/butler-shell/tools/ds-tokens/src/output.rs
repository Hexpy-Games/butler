//! Deterministic enums and scope data, split at item boundaries.
use crate::{
    css::Block,
    resolve,
    value::{Kind, Value},
};
use std::{
    collections::{BTreeMap, BTreeSet},
    fmt::Write as _,
    io::Write as _,
    process::{Command, Stdio},
};

const HEADER: &str = "// @generated by ds-tokens from tokens.css. Do not edit.\n";
type Values = BTreeMap<String, Value>;

pub(crate) fn generate(blocks: &[Block]) -> Result<BTreeMap<String, String>, String> {
    let scopes = resolve::scopes();
    let values = scopes
        .iter()
        .map(|s| resolve::resolve(blocks, *s))
        .collect::<Result<Vec<_>, _>>()?;
    let mut names = Vec::new();
    for block in blocks {
        for d in &block.declarations {
            if !names.contains(&d.name) {
                names.push(d.name.clone());
            }
        }
    }
    let kinds = names
        .iter()
        .map(|name| classify(name, &values))
        .collect::<Result<Vec<_>, _>>()?;
    let mut files = BTreeMap::new();
    let mut includes = format!(
        "{HEADER}use super::{{Ease, FilterOp, FontShorthand, Gradient, Keyword, Len, Op, Rgba, ShadowLayer, Table}};\n"
    );
    for kind in kinds.iter().copied().collect::<BTreeSet<_>>() {
        let names = names
            .iter()
            .zip(&kinds)
            .filter(|(_, k)| **k == kind)
            .map(|(n, _)| n.as_str())
            .collect::<Vec<_>>();
        let optional = values
            .iter()
            .any(|v| names.iter().any(|n| !v.contains_key(*n)));
        emit_kind(kind, &names, optional, &values, &mut files, &mut includes)?;
        println!(
            "{}: {} tokens; base light/dark/light-solid/dark-solid {:?}; {}",
            kind.name(),
            names.len(),
            (0..4)
                .map(|i| names.iter().filter(|n| values[i].contains_key(**n)).count())
                .collect::<Vec<_>>(),
            if optional { "optional" } else { "total" }
        );
    }
    files.insert("mod.rs".into(), includes);
    files
        .into_iter()
        .map(|(name, text)| {
            let text = format_rust(&text)?;
            if text.lines().count() > 450 {
                return Err(format!("generated {name} exceeds 450 lines"));
            }
            Ok((name, text))
        })
        .collect()
}

fn classify(name: &str, values: &[Values]) -> Result<Kind, String> {
    let mut kind = None;
    for value in values.iter().filter_map(|v| v.get(name)) {
        match kind {
            None => kind = Some(value.kind),
            Some(k) if k == value.kind => {}
            Some(Kind::Color) if value.kind == Kind::GradientToken => {
                kind = Some(Kind::GradientToken);
            }
            Some(Kind::GradientToken) if value.kind == Kind::Color => {}
            Some(Kind::Number) if value.code == "Len::Px(0.0)" => kind = Some(Kind::Length),
            Some(Kind::Length) if value.kind == Kind::Number && value.code == "0.0" => {}
            Some(Kind::Number) if value.kind == Kind::Length => kind = Some(Kind::Length),
            _ => return Err(format!("{name} changes kind between scopes")),
        }
    }
    kind.ok_or_else(|| format!("{name} is never set"))
}

fn value_code(value: Option<&Value>, kind: Kind, optional: bool) -> Result<String, String> {
    let code = match value {
        Some(v) if v.kind == kind => v.code.clone(),
        Some(v) if kind == Kind::GradientToken && v.kind == Kind::Color => {
            format!(
                "Gradient {{ angle_deg: 180.0, stops: &[({}, 0.0), ({}, 1.0)] }}",
                v.code, v.code
            )
        }
        Some(v) if kind == Kind::Length && v.kind == Kind::Number && v.code == "0.0" => {
            "Len::Px(0.0)".into()
        }
        Some(_) => return Err("incompatible token kinds".into()),
        None => return Ok("None".into()),
    };
    Ok(if optional {
        format!("Some({code})")
    } else {
        code
    })
}

fn emit_kind(
    kind: Kind,
    names: &[&str],
    optional: bool,
    values: &[Values],
    files: &mut BTreeMap<String, String>,
    includes: &mut String,
) -> Result<(), String> {
    let name = kind.name();
    let prefix = name.to_ascii_uppercase();
    let value_type = if optional {
        format!("Option<{}>", kind.value_type())
    } else {
        kind.value_type().into()
    };
    let value_type = value_type.replace("'static ", "");
    let mut items = vec![format!(
        "#[rustfmt::skip]\n#[derive(Clone, Copy, Debug, PartialEq, Eq)]\n#[repr(usize)]\npub enum {name} {{\n{}\n}}\n",
        names
            .iter()
            .map(|n| format!("    /** {n} */ {},", resolve::variant(n)))
            .collect::<Vec<_>>()
            .join("\n")
    )];
    let mut arrays = Vec::new();
    let mut interned: BTreeMap<String, String> = BTreeMap::new();
    for i in 0..values.len() {
        let code = array(kind, names, optional, values, i)?;
        let symbol = if let Some(existing) = interned.get(&code) {
            existing.clone()
        } else {
            let symbol = format!("{prefix}_{i}");
            let ty = if i < 4 {
                value_type.clone()
            } else {
                format!("({name}, {value_type})")
            };
            items.push(format!(
                "#[rustfmt::skip]\npub(in crate::tokens) static {symbol}: &[{ty}] = &[\n{code}];\n"
            ));
            interned.insert(code, symbol.clone());
            symbol
        };
        arrays.push(symbol);
    }
    items.push(format!("pub(in crate::tokens) static {prefix}: Table<{name}, {value_type}> = Table {{\n    base: [{}],\n    compact: [{}],\n    density: [{}],\n    reduced: [{}],\n}};\n", arrays[..4].join(", "), arrays[4..8].join(", "), arrays[8..32].join(", "), arrays[32..].join(", ")));
    write_parts(&name.to_ascii_lowercase(), name, &items, files, includes)?;
    Ok(())
}

fn array(
    kind: Kind,
    names: &[&str],
    optional: bool,
    values: &[Values],
    index: usize,
) -> Result<String, String> {
    let previous = if index < 4 {
        None
    } else if index < 8 {
        Some(index - 4)
    } else if index < 32 {
        Some((index - 8) / 6 + usize::from((index - 8) % 6 >= 3) * 4)
    } else {
        Some(index - 24)
    };
    let mut text = String::new();
    for name in names {
        let code = value_code(values[index].get(*name), kind, optional)?;
        if let Some(previous) = previous {
            if code == value_code(values[previous].get(*name), kind, optional)? {
                continue;
            }
            let _ = writeln!(
                text,
                "    ({}::{}, {code}),",
                kind.name(),
                resolve::variant(name)
            );
        } else {
            let _ = writeln!(text, "    {code},");
        }
    }
    Ok(text)
}

fn write_parts(
    name: &str,
    enum_name: &str,
    items: &[String],
    files: &mut BTreeMap<String, String>,
    includes: &mut String,
) -> Result<(), String> {
    let source = items.join("\n");
    let mut namespace = defined_names(&source)
        .into_iter()
        .map(|name| {
            let count = words(&source).filter(|word| *word == name).count();
            (name, count)
        })
        .collect::<BTreeMap<_, _>>();
    namespace.extend(
        [
            "Length",
            "Number",
            "FontStack",
            "Ease",
            "FilterOp",
            "FontShorthand",
            "Gradient",
            "Keyword",
            "Len",
            "Op",
            "Rgba",
            "ShadowLayer",
            "Table",
        ]
        .map(|name| (name.to_owned(), 0)),
    );
    let mut part = 0;
    let mut text = String::from(HEADER);
    for item in items {
        if item.lines().count() + 1 > 450 {
            return Err(format!("generated {name} item exceeds 450 lines"));
        }
        if text.lines().count() + item.lines().count() > 450 {
            insert_part(name, enum_name, part, text, files, includes, &namespace);
            part += 1;
            text = String::from(HEADER);
        }
        text.push_str(item);
    }
    insert_part(name, enum_name, part, text, files, includes, &namespace);
    Ok(())
}

fn insert_part(
    name: &str,
    enum_name: &str,
    part: usize,
    text: String,
    files: &mut BTreeMap<String, String>,
    includes: &mut String,
    namespace: &BTreeMap<String, usize>,
) {
    let suffix = char::from(b'a' + u8::try_from(part).unwrap_or_default());
    let file = format!("{name}_{suffix}.rs");
    let module = file.trim_end_matches(".rs");
    let _ = writeln!(includes, "mod {module};");
    if part == 0 {
        let _ = writeln!(includes, "pub use {module}::{enum_name};");
    }
    let symbols = text
        .lines()
        .filter_map(|line| line.strip_prefix("pub(in crate::tokens) static "))
        .filter_map(|line| line.split(':').next())
        .filter(|symbol| {
            *symbol == enum_name.to_ascii_uppercase()
                || namespace.get(*symbol).copied().unwrap_or_default()
                    > words(&text).filter(|word| word == symbol).count()
        })
        .collect::<Vec<_>>();
    if symbols.is_empty() {
        files.insert(file, text);
        return;
    }
    {
        let _ = writeln!(
            includes,
            "pub(super) use {module}::{{{}}};",
            symbols.join(", ")
        );
        let defined = defined_names(&text);
        let used = text
            .split(|c: char| !c.is_ascii_alphanumeric() && c != '_')
            .collect::<BTreeSet<_>>();
        let imports = namespace
            .keys()
            .filter(|n| used.contains(n.as_str()) && !defined.contains(*n))
            .cloned()
            .collect::<Vec<_>>();
        let import = format!("use super::{{{}}};\n", imports.join(", "));
        files.insert(file, text.replacen(HEADER, &format!("{HEADER}{import}"), 1));
    }
}

fn format_rust(text: &str) -> Result<String, String> {
    let mut child = Command::new("rustfmt")
        .args([
            "--emit",
            "stdout",
            "--edition",
            "2024",
            "--config",
            "skip_children=true",
        ])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .map_err(|e| format!("starting rustfmt: {e}"))?;
    child
        .stdin
        .take()
        .ok_or("missing rustfmt stdin")?
        .write_all(text.as_bytes())
        .map_err(|e| e.to_string())?;
    let output = child.wait_with_output().map_err(|e| e.to_string())?;
    if !output.status.success() {
        return Err(String::from_utf8_lossy(&output.stderr).into_owned());
    }
    String::from_utf8(output.stdout).map_err(|e| e.to_string())
}

fn defined_names(text: &str) -> BTreeSet<String> {
    text.lines()
        .filter_map(|line| {
            line.strip_prefix("pub(in crate::tokens) static ")
                .or_else(|| line.strip_prefix("pub enum "))
                .and_then(|rest| {
                    rest.split(|c: char| !c.is_ascii_alphanumeric() && c != '_')
                        .next()
                })
                .map(str::to_owned)
        })
        .collect()
}

fn words(text: &str) -> impl Iterator<Item = &str> {
    text.split(|c: char| !c.is_ascii_alphanumeric() && c != '_')
}
