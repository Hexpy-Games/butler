fn table() -> impl Iterator<Item = (&'static str, Handler)> {
    let routes = ROUTES
        .iter()
        .copied()
        .chain(super::canon_sidebar::ROUTES.iter().copied());
    #[cfg(feature = "e2e-fixtures")]
    let routes = routes.chain(FIXTURE_ROUTES.iter().copied());
    routes
}
