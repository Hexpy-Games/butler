//! Transport route templates are also the only paths exposed in access logs.
use super::{HttpState, dispatch};
use axum::{Router, routing::any};
use std::sync::Arc;

pub(super) fn routes() -> Router<Arc<HttpState>> {
    let mut router = Router::new();
    for path in PATHS {
        router = router.route(path, any(dispatch));
    }
    router.fallback(any(dispatch))
}

